-- Shared PostgreSQL deployment. Run as an operator; the runtime role must not own these tables.
CREATE SCHEMA spunto;
REVOKE ALL ON SCHEMA spunto FROM PUBLIC;
CREATE TABLE public.spunto_account (
 id TEXT PRIMARY KEY, issuer TEXT NOT NULL, subject TEXT NOT NULL, email TEXT, display_name TEXT,
 created_at BIGINT NOT NULL DEFAULT (extract(epoch FROM clock_timestamp())*1000)::BIGINT,
 UNIQUE (issuer,subject)
);
CREATE TABLE public.spunto_workspace (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, created_by TEXT NOT NULL REFERENCES public.spunto_account(id),
 created_at BIGINT NOT NULL, personal BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE public.spunto_membership (
 workspace_id TEXT NOT NULL REFERENCES public.spunto_workspace(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES public.spunto_account(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK (role IN ('owner','editor','viewer')),
 PRIMARY KEY (workspace_id,user_id)
);
CREATE TABLE public.spunto_login_session (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES public.spunto_account(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL, revoked_at BIGINT
);
REVOKE ALL ON public.spunto_account, public.spunto_workspace,
 public.spunto_membership, public.spunto_login_session FROM PUBLIC;


CREATE TABLE spunto.meta (
 workspace_id TEXT NOT NULL DEFAULT nullif(current_setting('spunto.workspace_id',true),'') REFERENCES public.spunto_workspace(id) ON DELETE CASCADE,
