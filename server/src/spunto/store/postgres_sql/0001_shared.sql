 public.spunto_credential_locator, public.spunto_pairing FROM PUBLIC;
CREATE FUNCTION spunto.route_credential() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 IF TG_OP='DELETE' THEN
  DELETE FROM public.spunto_credential_locator WHERE id=OLD.id AND workspace_id=OLD.workspace_id;
  RETURN OLD;
 END IF;
 INSERT INTO public.spunto_credential_locator(id,workspace_id,user_id)
 VALUES(NEW.id,NEW.workspace_id,current_setting('spunto.user_id'));
 RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION spunto.route_credential() FROM PUBLIC;
CREATE TRIGGER credential_locator_insert AFTER INSERT ON spunto.credential
 FOR EACH ROW EXECUTE FUNCTION spunto.route_credential();
CREATE TRIGGER credential_locator_delete AFTER DELETE ON spunto.credential
 FOR EACH ROW EXECUTE FUNCTION spunto.route_credential();
